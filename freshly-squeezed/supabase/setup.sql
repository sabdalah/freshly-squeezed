-- Run once in the Supabase SQL Editor.
create table if not exists public.drinks (
  id bigint generated by default as identity primary key,
  name text not null check (length(trim(name)) > 0),
  description text not null default '',
  price numeric(10,2) not null check (price >= 0),
  available boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);
alter table public.drinks enable row level security;
-- Everyone may view the menu. Only a specifically allowlisted user can edit.
create policy "Public can read drinks" on public.drinks for select to anon, authenticated using (true);
create table if not exists public.admin_users (user_id uuid primary key references auth.users(id) on delete cascade);
alter table public.admin_users enable row level security;
create policy "Admin can see own authorization" on public.admin_users for select to authenticated using (user_id = (select auth.uid()));
create policy "Admin can insert drinks" on public.drinks for insert to authenticated with check (exists (select 1 from public.admin_users where user_id = (select auth.uid())));
create policy "Admin can update drinks" on public.drinks for update to authenticated using (exists (select 1 from public.admin_users where user_id = (select auth.uid()))) with check (exists (select 1 from public.admin_users where user_id = (select auth.uid())));
create policy "Admin can delete drinks" on public.drinks for delete to authenticated using (exists (select 1 from public.admin_users where user_id = (select auth.uid())));
insert into public.drinks (id,name,description,price,available,sort_order) values
(1,'Banana Berry','Strawberry, banana, apple',8.00,true,1),
(2,'Red Mix','Red apple, Strawberry',8.00,true,2)
on conflict (id) do nothing;
select setval(pg_get_serial_sequence('public.drinks','id'), (select max(id) from public.drinks));
